def origin():
    """The address to name in links: the app's registered address, else wherever Anvil publishes it."""
    if SEO.get("site"):
        return SEO["site"].rstrip("/")
    try:
        return anvil.server.get_app_origin("published").rstrip("/")
    except Exception:
        return anvil.server.get_app_origin().rstrip("/")


def robots_txt(o):
    lines = ["# robots.txt for %s. Search engines and AI assistants are welcome to read and cite this site." % SEO["name"],
             "User-agent: *", "Allow: /"]
    lines += ["Disallow: %s" % p for p in SEO.get("disallow", [])]
    lines += ["", "# AI search and answer engines, named so it's clear they are welcome too"]
    lines += ["User-agent: %s" % b for b in AI_BOTS]
    lines += ["Allow: /"] + ["Disallow: %s" % p for p in SEO.get("disallow", [])]
    lines += ["", "Sitemap: %s/sitemap.xml" % o, ""]
    return "\n".join(lines)


def sitemap_xml(o):
    urls = [("/", "1.0"), ("/about", "0.8")] + [(p, "0.6") for p in SEO.get("sitemap_extra", [])]
    rows = ["<url><loc>%s%s</loc><lastmod>%s</lastmod><priority>%s</priority></url>"
            % (html.escape(o), html.escape(p), SEO["updated"], pr) for p, pr in urls]
    return ('<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
            + "\n".join(rows) + "\n</urlset>\n")


